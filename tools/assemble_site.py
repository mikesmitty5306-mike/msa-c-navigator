"""Assemble only the static frontend and validated public contract into a deployable site."""
import argparse
from pathlib import Path
import shutil
import sys
import tempfile
import json

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from msac.export.validate import validate_export


def assemble(web, data, out):
    web,data,out = (Path(p).resolve() for p in (web,data,out))
    if not (web/'index.html').is_file():
        raise ValueError('Static frontend must contain index.html')
    if out in (web,data) or web.is_relative_to(out) or data.is_relative_to(out) or out.is_relative_to(web) or out.is_relative_to(data):
        raise ValueError('Output and source directories must be separate')
    if out.exists() and any(out.iterdir()) and not (out/'.msac-site').exists():
        raise ValueError('Refusing to replace an unrecognized output directory')
    validate_export(data)
    # Explicit public files only. Reject symlinks and unlisted data rather than copying secrets.
    for source in (web,data):
        if any(p.is_symlink() for p in source.rglob('*')):
            raise ValueError('Symlinks are not permitted in deployable sources')
    out.parent.mkdir(parents=True,exist_ok=True)
    pending = Path(tempfile.mkdtemp(prefix='.site-',dir=out.parent))
    try:
        for path in web.rglob('*'):
            if path.is_file():
                relative = path.relative_to(web)
                if any(part.startswith('.') for part in relative.parts) or path.suffix in ('.sqlite3','.pem'):
                    continue
                # /data comes only from the validated public export, never web diagnostics.
                if relative.parts[0]=='data' or path.name=='maintenance-internal.json':
                    continue
                if path.suffix=='.json':
                    value = json.loads(path.read_text(encoding='utf-8'))
                    if isinstance(value,dict) and ('refresh_runs' in value or 'trials_data_timestamp' in value):
                        continue
                target = pending/relative
                target.parent.mkdir(parents=True,exist_ok=True)
                shutil.copyfile(path,target)
        meta = json.loads((data/'meta.json').read_text(encoding='utf-8'))
        for name in ['meta.json',*meta['files']]:
            source = (data/name).resolve()
            if not source.is_relative_to(data):
                raise ValueError('Unsafe manifest path')
            target = pending/'data'/name
            target.parent.mkdir(parents=True,exist_ok=True)
            shutil.copyfile(source,target)
        (pending/'.nojekyll').touch()
        (pending/'.msac-site').write_text('Generated by tools/assemble_site.py\n',encoding='utf-8')
        if out.exists():
            shutil.rmtree(out)
        pending.rename(out)
    finally:
        if pending.exists():
            shutil.rmtree(pending)
    return out


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--web',type=Path,default=ROOT/'web')
    parser.add_argument('--data',type=Path,default=ROOT/'public-data')
    parser.add_argument('--out',type=Path,default=ROOT/'_site')
    args = parser.parse_args(argv)
    print(assemble(args.web,args.data,args.out))


if __name__=='__main__':
    main()
